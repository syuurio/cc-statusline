/**
 * generateScript(config) → string
 *
 * Pure function: takes a config object and returns a complete,
 * self-contained bash script string. No I/O.
 */

import { DEFAULT_CONFIG } from './defaults.js'

const BAR_STYLES = {
  thin:  { filled: '━', empty: '─' },
  dot:   { filled: '●', empty: '○' },
  block: { filled: '█', empty: '░' },
}

const COLOR_SCHEMES = {
  default: {
    C_RESET:      "\\033[0m",
    C_BOLD:       "\\033[1m",
    C_DIM:        "\\033[2m",
    C_PURPLE:     "\\033[38;5;141m",
    C_BLUE:       "\\033[38;5;75m",
    C_GREEN:      "\\033[38;5;114m",
    C_YELLOW:     "\\033[38;5;221m",
    C_RED:        "\\033[38;5;204m",
    C_GRAY:       "\\033[38;5;245m",
    C_GRAY_LIGHT: "\\033[38;5;250m",
    C_CYAN:       "\\033[38;5;116m",
    C_ORANGE:     "\\033[38;5;215m",
  },
  'traffic-light': {
    C_RESET:      "\\033[0m",
    C_BOLD:       "\\033[1m",
    C_DIM:        "\\033[2m",
    C_PURPLE:     "\\033[38;5;114m",  // green
    C_BLUE:       "\\033[38;5;114m",  // green
    C_GREEN:      "\\033[38;5;114m",
    C_YELLOW:     "\\033[38;5;221m",
    C_RED:        "\\033[38;5;204m",
    C_GRAY:       "\\033[38;5;245m",
    C_GRAY_LIGHT: "\\033[38;5;250m",
    C_CYAN:       "\\033[38;5;114m",  // green
    C_ORANGE:     "\\033[38;5;221m",  // yellow
  },
  monochrome: {
    C_RESET:      "",
    C_BOLD:       "",
    C_DIM:        "",
    C_PURPLE:     "",
    C_BLUE:       "",
    C_GREEN:      "",
    C_YELLOW:     "",
    C_RED:        "",
    C_GRAY:       "",
    C_GRAY_LIGHT: "",
    C_CYAN:       "",
    C_ORANGE:     "",
  },
}

function has(fields, name) {
  return fields.includes(name)
}

export function generateScript(config) {
  const {
    fields = DEFAULT_CONFIG.fields,
    separator = DEFAULT_CONFIG.separator,
    colorScheme = DEFAULT_CONFIG.colorScheme,
    barStyle = DEFAULT_CONFIG.barStyle,
    thresholds = DEFAULT_CONFIG.thresholds,
  } = config

  const colors = COLOR_SCHEMES[colorScheme] || COLOR_SCHEMES.default
  const bar = BAR_STYLES[barStyle] || BAR_STYLES.thin
  const needsRate = has(fields, 'rateBar') || has(fields, 'resetTimes')

  const lines = []
  const push = (s) => lines.push(s)

  // ── Preamble ────────────────────────────────────────────────────────────
  push(`#!/bin/bash`)
  push(`# cc-statusline — generated by cc-statusline wizard`)
  push(`# https://github.com/syuurio/cc-statusline`)
  push(``)

  // Colors
  push(`# Colors`)
  for (const [name, val] of Object.entries(colors)) {
    if (val === '') {
      push(`${name}=''`)
    } else {
      push(`${name}=$'${val}'`)
    }
  }
  push(``)

  // Icons / Separator
  push(`# Icons / Separator`)
  push(`ICON_MODEL="🤖"`)
  push(`ICON_SEPARATOR="${separator}"`)
  push(``)

  // Thresholds
  push(`# Thresholds`)
  push(`USAGE_WARN=${thresholds.warn}`)
  push(`USAGE_DANGER=${thresholds.danger}`)
  push(``)

  // Platform detection (only needed for date formatting in resetTimes)
  if (has(fields, 'resetTimes')) {
    push(`# Platform detection`)
    push(`_IS_MACOS=0`)
    push(`[[ "$(uname -s)" == "Darwin" ]] && _IS_MACOS=1`)
    push(``)
  }

  // ── Helper functions ────────────────────────────────────────────────────
  push(`# ══════════════════════════════════════════════════════════════════`)
  push(`# HELPER FUNCTIONS`)
  push(`# ══════════════════════════════════════════════════════════════════`)
  push(``)

  // to_int: truncate a numeric string to an integer; anything else becomes empty
  if (has(fields, 'ctxBar') || has(fields, 'tokens') || needsRate) {
    push(`to_int() {`)
    push(`    local v="\${1%.*}"`)
    push(`    [[ "$v" =~ ^-?[0-9]+$ ]] && echo "$v"`)
    push(`}`)
    push(``)
  }

  // format_tokens (needed if tokens field is selected)
  if (has(fields, 'tokens')) {
    push(`format_tokens() {`)
    push(`    local num=$1`)
    push(`    if [[ -z "$num" ]] || [[ "$num" == "null" ]]; then`)
    push(`        echo "0"`)
    push(`        return`)
    push(`    fi`)
    push(`    if [[ "$num" -ge 1000000 ]]; then`)
    push(`        printf "%.1fM" "$(echo "scale=1; $num / 1000000" | bc)"`)
    push(`    elif [[ "$num" -ge 1000 ]]; then`)
    push(`        printf "%.1fK" "$(echo "scale=1; $num / 1000" | bc)"`)
    push(`    else`)
    push(`        echo "$num"`)
    push(`    fi`)
    push(`}`)
    push(``)
  }

  // get_usage_color (needed for bars)
  if (has(fields, 'ctxBar') || needsRate) {
    push(`get_usage_color() {`)
    push(`    local pct=$1`)
    push(`    if [[ -z "$pct" ]]; then`)
    push(`        echo "$C_GRAY"`)
    push(`    elif [[ "$pct" -ge "$USAGE_DANGER" ]]; then`)
    push(`        echo "$C_RED"`)
    push(`    elif [[ "$pct" -ge "$USAGE_WARN" ]]; then`)
    push(`        echo "$C_YELLOW"`)
    push(`    else`)
    push(`        echo "$C_GREEN"`)
    push(`    fi`)
    push(`}`)
    push(``)
  }

  // progress_bar (needed for any bar)
  if (has(fields, 'ctxBar') || has(fields, 'rateBar')) {
    push(`progress_bar() {`)
    push(`    local pct=\${1:-0}`)
    push(`    local width=\${2:-5}`)
    push(`    [[ "$pct" -lt 0 ]] && pct=0`)
    push(`    [[ "$pct" -gt 100 ]] && pct=100`)
    push(`    local filled=$((pct * width / 100))`)
    push(`    local empty=$((width - filled))`)
    push(`    local bar=""`)
    push(`    for ((i=0; i<filled; i++)); do bar+="${bar.filled}"; done`)
    push(`    for ((i=0; i<empty; i++)); do bar+="${bar.empty}"; done`)
    push(`    echo "$bar"`)
    push(`}`)
    push(``)
  }

  // format_reset_time (needed for resetTimes) — stdin provides Unix epoch
  if (has(fields, 'resetTimes')) {
    push(`format_reset_time() {`)
    push(`    local epoch="$1" fmt="$2"`)
    push(`    [[ -z "$epoch" ]] || [[ "$epoch" == "null" ]] && return`)
    push(`    if [[ "$_IS_MACOS" == "1" ]]; then`)
    push(`        date -r "$epoch" +"$fmt" 2>/dev/null`)
    push(`    else`)
    push(`        date -d "@$epoch" +"$fmt" 2>/dev/null`)
    push(`    fi`)
    push(`}`)
    push(``)
  }

  // ── Main logic ──────────────────────────────────────────────────────────
  push(`# ══════════════════════════════════════════════════════════════════`)
  push(`# MAIN LOGIC`)
  push(`# ══════════════════════════════════════════════════════════════════`)
  push(``)

  push(`input=$(cat)`)
  push(`_jq() { echo "$input" | jq -r "$1" 2>/dev/null; }`)
  push(``)

  // Account label: the config dir in use is the source of truth
  // (~/.claude-work → work). Only the default ~/.claude falls back to
  // DEV_PROFILE, then "default", so the label never names the wrong account.
  if (has(fields, 'account')) {
    push(`_cfg_name=$(basename "\${CLAUDE_CONFIG_DIR:-.claude}")`)
    push(`case "$_cfg_name" in`)
    push(`    .claude) account="\${DEV_PROFILE:-default}" ;;`)
    push(`    .claude-*) account="\${_cfg_name#.claude-}" ;;`)
    push(`    *) account="\${_cfg_name#.}" ;;`)
    push(`esac`)
    push(``)
  }

  // Parse only the fields we need
  if (has(fields, 'model')) {
    push(`model=$(_jq '.model.display_name // empty')`)
  }
  if (has(fields, 'effort')) {
    push(`effort=$(_jq '.effort.level // empty')`)
  }
  if (has(fields, 'dir') || has(fields, 'git')) {
    push(`cwd=$(_jq '.workspace.current_dir // empty')`)
  }
  if (has(fields, 'ctxBar') || has(fields, 'tokens')) {
    push(`used_pct=$(_jq '.context_window.used_percentage // empty')`)
  }
  if (has(fields, 'tokens')) {
    push(`context_size=$(_jq '.context_window.context_window_size // 200000')`)
    push(`total_input=$(_jq '.context_window.total_input_tokens // 0')`)
  }
  if (has(fields, 'cost')) {
    push(`session_cost=$(_jq '.cost.total_cost_usd // 0')`)
  }
  push(``)

  // Context usage calculation (used_percentage may be a float or null)
  if (has(fields, 'ctxBar') || has(fields, 'tokens')) {
    push(`used_pct=$(to_int "$used_pct")`)
    push(`used_pct=\${used_pct:-0}`)
    push(``)
  }

  // total_input_tokens is the input side of the current context window;
  // fall back to the percentage when it is not reported yet.
  if (has(fields, 'tokens')) {
    push(`ctx_tokens=$(to_int "$total_input")`)
    push(`if [[ -z "$ctx_tokens" || "$ctx_tokens" -eq 0 ]]; then`)
    push(`    ctx_tokens=$(( used_pct * \${context_size:-200000} / 100 ))`)
    push(`fi`)
    push(``)
  }

  // Rate limit fields (from stdin JSON, available for Claude.ai Pro/Max subscribers).
  // Each window may be absent independently, e.g. after its resets_at passes.
  if (needsRate) {
    push(`five_int=$(to_int "$(_jq '.rate_limits.five_hour.used_percentage // empty')")`)
    push(`seven_int=$(to_int "$(_jq '.rate_limits.seven_day.used_percentage // empty')")`)
  }
  if (has(fields, 'resetTimes')) {
    push(`five_hour_reset=$(_jq '.rate_limits.five_hour.resets_at // empty')`)
    push(`seven_day_reset=$(_jq '.rate_limits.seven_day.resets_at // empty')`)
    push(`five_reset_fmt=$(format_reset_time "\${five_hour_reset:-}" "%H:%M %-d %b")`)
    push(`seven_reset_fmt=$(format_reset_time "\${seven_day_reset:-}" "%H:%M %-d %b")`)
  }
  push(``)

  // ── Build output ────────────────────────────────────────────────────────
  push(`# ══════════════════════════════════════════════════════════════════`)
  push(`# BUILD OUTPUT`)
  push(`# ══════════════════════════════════════════════════════════════════`)
  push(``)
  push(`line1=""`)
  push(`line2=""`)
  push(`line3=""`)
  push(`SEP=" \${C_GRAY}\${ICON_SEPARATOR}\${C_RESET} "`)
  push(`# addN <text>: append a segment to lineN, inserting SEP between segments`)
  push(`add1() { [[ -n "$line1" ]] && line1+="$SEP"; line1+="$1"; }`)
  push(`add2() { [[ -n "$line2" ]] && line2+="$SEP"; line2+="$1"; }`)
  push(`add3() { [[ -n "$line3" ]] && line3+="$SEP"; line3+="$1"; }`)
  push(``)

  // ── LINE 1 ──────────────────────────────────────────────────────────────
  push(`# LINE 1: Info fields`)

  if (has(fields, 'account')) {
    push(`if [[ "$account" == "default" || "$account" == "personal" ]]; then`)
    push(`    add1 "\${C_GRAY}◆ \${account}\${C_RESET}"`)
    push(`else`)
    push(`    add1 "\${C_BOLD}\${C_ORANGE}◆ \${account}\${C_RESET}"`)
    push(`fi`)
  }

  if (has(fields, 'model')) {
    push(`if [[ -n "$model" ]]; then`)
    push(`    short_model=$(echo "$model" | sed 's/Claude //')`)
    push(`    add1 "\${C_PURPLE}\${ICON_MODEL} \${short_model}\${C_RESET}"`)
    push(`fi`)
  }

  // Absent when the model does not support effort; higher levels stand out more
  if (has(fields, 'effort')) {
    push(`case "$effort" in`)
    push(`    high) add1 "\${C_CYAN}⚡ \${effort}\${C_RESET}" ;;`)
    push(`    xhigh) add1 "\${C_ORANGE}⚡ \${effort}\${C_RESET}" ;;`)
    push(`    max) add1 "\${C_BOLD}\${C_ORANGE}⚡ \${effort}\${C_RESET}" ;;`)
    push(`    ?*) add1 "\${C_GRAY}⚡ \${effort}\${C_RESET}" ;;`)
    push(`esac`)
  }

  if (has(fields, 'dir')) {
    push(`if [[ -n "$cwd" ]]; then`)
    push(`    add1 "\${C_BLUE}$(basename "$cwd")\${C_RESET}"`)
    push(`fi`)
  }

  if (has(fields, 'git')) {
    push(`if [[ -n "$cwd" ]] && [[ -d "$cwd" ]]; then`)
    push(`    git_branch=$(git -C "$cwd" branch --show-current 2>/dev/null)`)
    push(`    if [[ -n "$git_branch" ]]; then`)
    push(`        git_status=$(git -C "$cwd" status --porcelain 2>/dev/null)`)
    push(`        if [[ -n "$git_status" ]]; then`)
    push(`            add1 "\${C_YELLOW}\${git_branch}*\${C_RESET}"`)
    push(`        else`)
    push(`            add1 "\${C_GREEN}\${git_branch}\${C_RESET}"`)
    push(`        fi`)
    push(`    fi`)
    push(`fi`)
  }

  if (has(fields, 'tokens')) {
    push(`formatted_ctx=$(format_tokens "$ctx_tokens")`)
    push(`formatted_max=$(format_tokens "$context_size")`)
    push(`add1 "\${C_CYAN}\${formatted_ctx}/\${formatted_max}\${C_RESET}"`)
  }

  if (has(fields, 'cost')) {
    push(`formatted_cost=$(printf "%.2f" "$session_cost")`)
    push(`add1 "\${C_ORANGE}\\$\${formatted_cost}\${C_RESET}"`)
  }

  push(``)

  // ── LINE 2 ──────────────────────────────────────────────────────────────
  if (has(fields, 'ctxBar') || has(fields, 'rateBar')) {
    push(`# LINE 2: Bars`)

    if (has(fields, 'ctxBar')) {
      push(`ctx_color=$(get_usage_color "$used_pct")`)
      push(`ctx_bar=$(progress_bar "$used_pct" 10)`)
      push(`add2 "\${C_GRAY_LIGHT}[ctx]\${C_RESET} \${ctx_color}\${ctx_bar} \${used_pct}%\${C_RESET}"`)
    }

    // A missing window renders as a placeholder so the layout does not jump
    // when rate_limits first arrives after the session's first API response.
    if (has(fields, 'rateBar')) {
      push(`if [[ -n "$five_int" ]]; then`)
      push(`    add2 "\${C_GRAY_LIGHT}[5h]\${C_RESET} $(get_usage_color "$five_int")$(progress_bar "$five_int" 10) \${five_int}%\${C_RESET}"`)
      push(`else`)
      push(`    add2 "\${C_GRAY_LIGHT}[5h]\${C_RESET} \${C_GRAY}$(progress_bar 0 10) --%\${C_RESET}"`)
      push(`fi`)
      push(`if [[ -n "$seven_int" ]]; then`)
      push(`    add2 "\${C_GRAY_LIGHT}[7d]\${C_RESET} $(get_usage_color "$seven_int")$(progress_bar "$seven_int" 10) \${seven_int}%\${C_RESET}"`)
      push(`else`)
      push(`    add2 "\${C_GRAY_LIGHT}[7d]\${C_RESET} \${C_GRAY}$(progress_bar 0 10) --%\${C_RESET}"`)
      push(`fi`)
    }
    push(``)
  }

  // ── LINE 3 ──────────────────────────────────────────────────────────────
  if (has(fields, 'resetTimes')) {
    push(`# LINE 3: Reset times`)
    push(`add3 "\${C_GRAY_LIGHT}[↻ 5h]\${C_RESET} \${C_GRAY}\${five_reset_fmt:-—}\${C_RESET}"`)
    push(`add3 "\${C_GRAY_LIGHT}[↻ 7d]\${C_RESET} \${C_GRAY}\${seven_reset_fmt:-—}\${C_RESET}"`)
    push(``)
  }

  // ── Output ──────────────────────────────────────────────────────────────
  // Empty lines are skipped; the last printed tree line gets the ╰ corner.
  push(`out="$line1"`)
  push(`if [[ -n "$line2" ]]; then`)
  push(`    if [[ -n "$line3" ]]; then _corner="├"; else _corner="╰"; fi`)
  push(`    out+=$'\\n'"\${C_GRAY}\${_corner}\${C_RESET} \${line2}"`)
  push(`fi`)
  push(`if [[ -n "$line3" ]]; then`)
  push(`    out+=$'\\n'"\${C_GRAY}╰\${C_RESET} \${line3}"`)
  push(`fi`)
  push(`printf "%s" "$out"`)

  return lines.join('\n') + '\n'
}
